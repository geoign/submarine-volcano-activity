"""Render docs/METHODS.en.md and docs/METHODS.ja.md into about.html.

    python tools/build_about.py

The two texts are the source; about.html is generated and holds both, one shown at a time by the
language switch. Only the Markdown these texts use is understood: headings, paragraphs, bullet
and numbered lists, tables, `code`, and bare URLs and e-mail addresses.
"""

from __future__ import annotations

import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Methods and data · Submarine Volcano Activity Database</title>
<meta name="description" content="How the Submarine Volcano Activity Database is made: targets, imagery, screening, review, classes, limits, data files, sources and terms of use.">
<link rel="icon" href="assets/icon.svg" type="image/svg+xml">
<link rel="stylesheet" href="assets/css/style.css?v=1">
</head>
<body data-title="nav.about">
<!-- Generated by tools/build_about.py from docs/METHODS.en.md and docs/METHODS.ja.md. Edit those. -->
<main class="wrap narrow prose">
<div data-lang-block="en" lang="en">
{en}
</div>
<div data-lang-block="ja" lang="ja">
{ja}
</div>
</main>
<script type="module">
import {{ renderChrome }} from "./assets/js/common.js";
renderChrome("about");
</script>
</body>
</html>
"""


def inline(text: str) -> str:
    out = html.escape(text, quote=False)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    out = re.sub(r"(?<![\w/\"=>])(https?://[^\s<)`]+[^\s<)`.,])(?![^<]*</code>)", r'<a href="\1">\1</a>', out)
    out = re.sub(r"(?<![\w.])([\w.+-]+@[\w-]+\.[\w.-]+[a-z])", r'<a href="mailto:\1">\1</a>', out)
    return out


def render(md: str, lang: str) -> str:
    joiner = "" if lang == "ja" else " "
    out, para, lines = [], [], md.splitlines()

    def flush() -> None:
        if para:
            out.append("<p>" + inline(joiner.join(para)) + "</p>")
            para.clear()

    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        if not line:
            flush()
        elif line.startswith("#"):
            flush()
            level = len(line) - len(line.lstrip("#"))
            out.append(f"<h{level}>{inline(line[level:].strip())}</h{level}>")
        elif line.startswith("|"):
            flush()
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            i -= 1
            head, body = rows[0], [r for r in rows[2:]]
            out.append("<table><thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead><tbody>")
            out += ["<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in body]
            out.append("</tbody></table>")
        elif re.match(r"^(- |\d+\. )", line):
            flush()
            tag = "ul" if line.startswith("- ") else "ol"
            out.append(f"<{tag}>")
            while i < len(lines) and re.match(r"^(- |\d+\. )", lines[i]):
                out.append("<li>" + inline(re.sub(r"^(- |\d+\. )", "", lines[i].rstrip())) + "</li>")
                i += 1
            i -= 1
            out.append(f"</{tag}>")
        else:
            para.append(line)
        i += 1
    flush()
    return "\n".join(out)


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    en = render((ROOT / "docs/METHODS.en.md").read_text(encoding="utf-8"), "en")
    ja = render((ROOT / "docs/METHODS.ja.md").read_text(encoding="utf-8"), "ja")
    (ROOT / "about.html").write_text(PAGE.format(en=en, ja=ja), encoding="utf-8", newline="\n")
    print(f"about.html: {len(en)} + {len(ja)} characters of HTML")


if __name__ == "__main__":
    main()
